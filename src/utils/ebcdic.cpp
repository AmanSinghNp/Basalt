std::string EbcdicConverter::to_ascii(const void* data, size_t length) {
    if (!data || length == 0) return "";
    
    std::string result(length, 0);
    to_ascii(data, result.data(), length);
    return result;
}

void EbcdicConverter::to_ascii(const void* src, char* dst, size_t length) {
    const unsigned char* bytes = static_cast<const unsigned char*>(src);
    for (size_t i = 0; i < length; ++i) {
        dst[i] = ebcdic_to_ascii_table[bytes[i]];
    }
}

